def _archive_bytes() -> bytes:
    raw = base64.b64decode("".join(ARCHIVE_B64.split()))
    digest = hashlib.sha256(raw).hexdigest()
    if digest != EXPECTED_SHA256:
        raise RuntimeError(f"Niezgodność sumy kontrolnej SHA-256: oczekiwano {EXPECTED_SHA256}, otrzymano {digest}")
    return raw


def _merge_operator_tools(target_root: Path, backup_dir: Path) -> str:
    original = target_root / "operator_tools.py"
    patch_1_3 = target_root / "operator_tools_sections_1_to_3.py"
    if not patch_1_3.is_file():
        return "pominięto (brak pliku łatki)"
    if not original.is_file():
        return "pominięto (brak operator_tools.py w katalogu docelowym; pozostawiono operator_tools_sections_1_to_3.py)"

    orig_lines = original.read_text(encoding="utf-8").splitlines()
    patch_text = patch_1_3.read_text(encoding="utf-8")

    cut_index = None
    for idx, line in enumerate(orig_lines):
        if '"truncated": len(raw) >= 1_000_000}' in line:
            cut_index = idx + 1
            break

    if cut_index is None:
        return "pominięto (nie znaleziono granicy sekcji 3 w operator_tools.py)"

    tail = "\n".join(orig_lines[cut_index:])
    merged = patch_text.rstrip("\n") + "\n\n" + tail.lstrip("\n") + "\n"
    ast.parse(merged)

    backup_dir.mkdir(mode=0o700, parents=True, exist_ok=True)
    shutil.copy2(original, backup_dir / "operator_tools.py")
    original.write_text(merged, encoding="utf-8")
    patch_1_3.unlink(missing_ok=True)
    return f"połączono pomyślnie ({len(merged.splitlines())} linii)"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Instalator poprawek audytu i rozszerzeń F1-F5 dla Jarvisa.")
    parser.add_argument(
        "target",
        nargs="?",
        default=".",
        help="Ścieżka do katalogu projektu Jarvis (domyślnie: bieżący katalog '.').",
    )
    parser.add_argument(
        "--zip-only",
        action="store_true",
        help="Zapisz wyłącznie archiwum jarvis-aktualizacja-final.zip bez rozpakowywania.",
    )
    args = parser.parse_args(argv)

    payload = _archive_bytes()
    target_root = Path(args.target).expanduser().resolve()
    target_root.mkdir(parents=True, exist_ok=True)

    if args.zip_only:
        out_zip = target_root / "jarvis-aktualizacja-final.zip"
        out_zip.write_bytes(payload)
        print(f"[OK] Zapisano archiwum: {out_zip} ({len(payload)} bajtów, SHA-256 zweryfikowane).")
        return 0

    stamp = int(time.time())
    backup_dir = target_root / f".jarvis-backup-{stamp}"
    extracted = []

    with zipfile.ZipFile(io.BytesIO(payload), "r") as zf:
        for info in zf.infolist():
            rel = Path(info.filename)
            if rel.is_absolute() or ".." in rel.parts:
                raise RuntimeError(f"Niebezpieczna ścieżka w archiwum: {info.filename}")
            dest = target_root / rel
            if dest.is_file() and rel.name != "operator_tools_sections_1_to_3.py":
                btarget = backup_dir / rel
                btarget.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
                shutil.copy2(dest, btarget)
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(zf.read(info.filename))
            mode = (info.external_attr >> 16) & 0o777
            if mode:
                try:
                    os.chmod(dest, mode)
                except OSError:
                    pass
            elif dest.suffix == ".sh":
                os.chmod(dest, stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH)
            extracted.append(str(rel))

    merge_status = _merge_operator_tools(target_root, backup_dir)
    print(f"[OK] Rozpakowano {len(extracted)} finalnych plików do: {target_root}")
    print(f"[OK] Scalanie operator_tools.py: {merge_status}")
    if backup_dir.exists():
        print(f"[OK] Kopia zapasowa poprzednich plików: {backup_dir}")
    print("[GOTOWE] Uruchom `./scripts/check.sh` w katalogu projektu Jarvis.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
